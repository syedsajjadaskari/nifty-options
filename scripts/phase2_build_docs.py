"""Generate docs/phase2/rule_registry.yaml, rule_registry.md and source_traceability.md.

Traceability is introspected, not hand-written: functions come from ``@implements`` registrations
and tests from ``@pytest.mark.rules(...)`` markers collected by pytest. A rule with no test is listed
as such; nothing is claimed that does not exist.
"""

from __future__ import annotations

import collections
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

import pytest  # noqa: E402

import nifty_trading.core.exit_policy  # noqa: E402,F401  (registers @implements)
import nifty_trading.strategies  # noqa: E402,F401
from nifty_trading.strategies.params import CANDIDATE_NOTES, RF_TARGET_STATUS, SOURCE  # noqa: E402
from nifty_trading.strategies.rule_data import RULES  # noqa: E402
from nifty_trading.strategies.rules import IMPLEMENTATIONS  # noqa: E402

DOCS = ROOT / "docs" / "phase2"


class _Collect:
    def __init__(self) -> None:
        self.tests: dict[str, list[str]] = collections.defaultdict(list)

    def pytest_collection_modifyitems(self, items):  # noqa: D401
        for it in items:
            ids: list[str] = []
            for m in it.iter_markers("rules"):
                ids += list(m.args)
            for rid in set(ids):
                self.tests[rid].append(it.nodeid.split("::", 1)[0].replace("tests/", "") + "::" + it.nodeid.split("::")[-1].split("[")[0])


def collect_tests() -> dict[str, list[str]]:
    c = _Collect()
    pytest.main(["--collect-only", "-q", "-p", "no:cacheprovider", str(ROOT / "tests")], plugins=[c])
    return {k: sorted(set(v)) for k, v in c.tests.items()}


def short(fn: str) -> str:
    return fn.replace("nifty_trading.", "")


def main() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    tests = collect_tests()
    funcs: dict[str, list[str]] = collections.defaultdict(list)
    for fn, ids in IMPLEMENTATIONS.items():
        for rid in ids:
            funcs[rid].append(short(fn))

    # ------------------------------------------------------------------ YAML
    header = {
        "registry_name": "NIFTY 50 Phase 2 rule registry",
        "scope": "NIFTY 50 index-price signals only. No options, no orders, no live execution. All point P&L is synthetic.",
        "classification_vocabulary": {
            "VERIFIED_EXPLICIT": "directly stated and objectively testable",
            "VERIFIED_QUALITATIVE": "directly stated but needs a mathematical interpretation",
            "CONFLICTING": "different sections give incompatible instructions",
            "UNRESOLVED": "necessary information not provided (was MISSING)",
            "PROPOSED_FOR_REVIEW": "engineering interpretation, NOT an original rule (was PROPOSED)",
            "USER_APPROVED": "authorised by the strategy owner (Phase 2.2: stop-loss research baseline only)",
        },
        "unresolved_flags": {"RF_TARGET_STATUS": RF_TARGET_STATUS, "RF_STOP_SELECTION": "SOURCE UNRESOLVED; research baseline 35 USER_APPROVED (EXE-STOP-001)", "PDR_STOP_SELECTION": "SOURCE UNRESOLVED; research baseline 35 USER_APPROVED (EXE-STOP-001)",
                             "TARGET2_ASSIGNMENT_PER_STRATEGY": "guide values configured (IRF 60, ORB 60, PDR 70, PDS 70); RF 60 PROPOSED_FOR_REVIEW; PDR/PDS guide-vs-report conflict recorded"},
        "source_constants_stated_in_documents": {k: v for k, v in SOURCE.__dict__.items()},
        "proposal_candidates": CANDIDATE_NOTES,
        "proposal_label": "PROPOSED_FOR_REVIEW",
    }
    rules = []
    for r in RULES:
        r2 = dict(r)
        r2["implemented_by"] = sorted(funcs.get(r["rule_id"], []))
        r2["tested_by"] = tests.get(r["rule_id"], [])
        rules.append(r2)
    (DOCS / "rule_registry.yaml").write_text(
        "# GENERATED by scripts/phase2_build_docs.py from src/nifty_trading/strategies/rule_data.py - do not edit by hand\n"
        + yaml.safe_dump({**header, "rules": rules}, sort_keys=False, allow_unicode=True, width=140))

    # ------------------------------------------------------------------ readable registry
    md = ["# Rule registry (readable)\n", "Generated from `rule_registry.yaml`. Classification: `VE` VERIFIED_EXPLICIT, `VQ` VERIFIED_QUALITATIVE, "
          "`CF` CONFLICTING, `MS` UNRESOLVED, `PR` PROPOSED_FOR_REVIEW. Page numbers are PDF pages (DOCX has no pagination: `n/a`).\n"]
    ab = {"VERIFIED_EXPLICIT": "VE", "VERIFIED_QUALITATIVE": "VQ", "CONFLICTING": "CF", "UNRESOLVED": "MS", "PROPOSED_FOR_REVIEW": "PR", "USER_APPROVED": "UA"}
    by = collections.defaultdict(list)
    for r in rules:
        by[r["strategy"]].append(r)
    for strat, rs in by.items():
        md += [f"\n## {strat}\n", "| Rule | Method | Class | Mand. | Source (page) | Rule (source wording, paraphrased) | Condition | Eval. time | Status | Unresolved |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for r in rs:
            md.append("| {id} | {m} | {c} | {mand} | {doc} p.{pg} | {d} | {math} | {t} | {st} | {u} |".format(
                id=r["rule_id"], m=r["method"], c=ab[r["classification"]], mand="Y" if r["mandatory"] else "N",
                doc=r["source_document"].replace(" ", "&nbsp;"), pg=r["source_page"], d=r["description"].replace("|", "/"),
                math=(r["mathematical_condition"] or "-").replace("|", "/"), t=r["evaluation_time"],
                st=r["implementation_status"], u="; ".join(r["unresolved_dependencies"]).replace("|", "/") or "-"))
    cnt = collections.Counter(r["classification"] for r in rules)
    md += ["\n## Counts\n", "| Classification | Rules |", "|---|---|", *(f"| {k} | {v} |" for k, v in sorted(cnt.items())), f"| **total** | **{len(rules)}** |"]
    (DOCS / "rule_registry.md").write_text("\n".join(md) + "\n")

    # ------------------------------------------------------------------ traceability
    tr = ["# Source-to-code traceability\n",
          "Generated by `scripts/phase2_build_docs.py`. **Functions** come from `@implements(...)` registrations in the code; **tests** come from "
          "`@pytest.mark.rules(...)` markers collected by pytest. Nothing is hand-edited, so a blank cell is a real gap.\n",
          "Chain: **Source PDF -> page -> rule ID -> algorithm (condition) -> Python function -> unit test**. `Class` as in the registry; "
          "rows whose class is PR/MS/CF rest on an engineering interpretation, never on a verified rule.\n"]
    gaps = []
    for strat, rs in by.items():
        tr += [f"\n## {strat}\n", "| Source | Page | Rule ID | Class | Algorithm | Python function | Unit test |", "|---|---|---|---|---|---|---|"]
        for r in rs:
            fn = "<br>".join(f"`{f}`" for f in r["implemented_by"]) or "-"
            ts = "<br>".join(f"`{t}`" for t in r["tested_by"][:4]) + (f"<br>(+{len(r['tested_by']) - 4} more)" if len(r["tested_by"]) > 4 else "") or "-"
            tr.append("| {doc} | {pg} | {id} | {c} | {a} | {f} | {t} |".format(
                doc=r["source_document"].replace(" ", "&nbsp;"), pg=r["source_page"], id=r["rule_id"], c=ab[r["classification"]],
                a=(r["mathematical_condition"] or r["description"]).replace("|", "/")[:150], f=fn, t=ts))
            if r["implementation_status"] != "SPECIFICATION_ONLY" and r["implementation_status"] != "NOT_IMPLEMENTED_UNRESOLVED" and not r["tested_by"]:
                gaps.append(r["rule_id"])
    n_impl = sum(1 for r in rules if r["implemented_by"])
    n_test = sum(1 for r in rules if r["tested_by"])
    tr += ["\n## Coverage summary\n", f"- Rules in registry: **{len(rules)}**", f"- Rules with at least one implementing function: **{n_impl}**",
           f"- Rules with at least one unit test: **{n_test}**",
           f"- Implemented rules without any test: **{len(gaps)}** {sorted(gaps) if gaps else ''}",
           "- Rules marked `NOT_IMPLEMENTED_UNRESOLVED` have no algorithm by design (the source does not define them).",
           "- `PROPOSED` thresholds are engineering interpretations (see `ambiguous_rules.md`); a passing test proves the code matches the "
           "interpretation, **not** that the interpretation is the author's rule."]
    (DOCS / "source_traceability.md").write_text("\n".join(tr) + "\n")
    print({"rules": len(rules), "with_function": n_impl, "with_test": n_test, "implemented_untested": sorted(gaps)})


if __name__ == "__main__":
    main()
