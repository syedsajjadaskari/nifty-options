"""Phase 2.1: generate docs/phase2/data_provenance.md from the real manifests, request logs and hashes (no hand-typed numbers)."""

from __future__ import annotations

import glob
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]



def _same_as_archive() -> str:
    """Compare the live Phase 1 metadata files with the unchanged archive by SHA-256 instead of asserting they are untouched."""
    import hashlib

    arch = ROOT / "data" / "archive" / "phase1_original_20261101"
    out = []
    for name in ("nifty50_instrument.json", "download_manifest.json"):
        live, orig = ROOT / "data" / "metadata" / name, arch / name
        if not (live.exists() and orig.exists()):
            out.append(f"{name}: not comparable")
            continue
        same = hashlib.sha256(live.read_bytes()).hexdigest() == hashlib.sha256(orig.read_bytes()).hexdigest()
        out.append(f"{name} {'byte-identical to the archive' if same else 'DIFFERS from the archive'}")
    return "; ".join(out) + "."

def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    md = ["# Data provenance (generated by scripts/phase21_provenance.py)\n",
          "Every dataset, where it came from, its checksum, and what it is used for. Nothing was replaced: the original Phase 1 data is byte-identical to its archive.\n"]
    # ---- original + archive
    arch = ROOT / "data" / "archive" / "phase1_original_20261101"
    lines = (arch / "SHA256SUMS").read_text().splitlines()
    md += ["## 1. Original Phase 1 minute data (unchanged)\n",
           "Source: 5paisa historical API, 1-minute NIFTY 50 index (scrip 999920000, exchange N, segment C), downloaded 2026-11-01 by the Phase 1 pipeline (`data/metadata/download_manifest.json`).",
           f"Unchanged read-only archive: `{arch.relative_to(ROOT)}` ({len(lines)} files). Partition files in `data/processed/nifty50` compared with the archive by SHA-256:\n",
           "| partition | SHA-256 (archive) | identical to live file |", "|---|---|---|"]
    for line in lines:
        h, rel = line.split(maxsplit=1)
        if rel.startswith("./nifty50/"):
            live = ROOT / "data" / "processed" / rel[2:]
            md.append(f"| `{rel[2:]}` | `{h[:16]}…` | {'yes' if live.exists() and sha(live) == h else '**NO**'} |")
    # ---- raw re-downloads
    md += ["\n## 2. Fresh read-only re-downloads (Phase 2.1)\n", "Saved exactly as returned, before any cleaning, under `data/raw/redownload_<utc>/` with the request log. Same login, same endpoint, same parameters as Phase 1; order methods are disabled in `BrokerClient`.\n",
           "| directory | label | timeframe | from | to | rows | SHA-256 | purpose |", "|---|---|---|---|---|---|---|---|"]
    purpose = {"aug_1m": "target month (identical to stored)", "jul_1m_control": "control month (identical to stored)", "diag_jun_1m": "control month (identical to stored)",
               "diag_sep_1m": "diagnostic outside the analysis period (same auction pattern)", "diag_oct_1m": "diagnostic outside the analysis period (same auction pattern)",
               "aug_5m": "vendor 5-minute candles for August", "aug_1d": "vendor daily candles for August"}
    for d in sorted(glob.glob(str(ROOT / "data" / "raw" / "redownload_*"))):
        for e in json.loads((Path(d) / "request_log.json").read_text()):
            r = e["request"]
            pu = purpose.get(e["label"], "5-minute aggregation cross-check" if e["label"].startswith("m5_") else "daily series: official closes + 200-day history" if e["label"].startswith("daily_")
                             else "warm-up only (EMA seed)" if e["label"].startswith("warm_") else "")
            md.append(f"| `{Path(d).name}` | {e['label']} | {r['timeframe']} | {r['from_date']} | {r['to_date']} | {e.get('rows', '-')} | `{e.get('sha256', '-')[:16]}…` | {pu} |")
    # ---- new processed artefacts
    prov = json.loads((ROOT / "data" / "metadata" / "provenance_new_artifacts.json").read_text())
    md += ["\n## 3. New processed artefacts (additive; nothing overwritten)\n", "| artefact | rows | first | last | SHA-256 | use |", "|---|---|---|---|---|---|"]
    for a in prov["artifacts"]:
        md.append(f"| `{a['artifact']}` | {a['rows']} | {a['first'][:10]} | {a['last'][:10]} | `{a['sha256'][:16]}…` | {a['use']} |")
    md.append("\nEach artefact lists its source raw files and their hashes in `data/metadata/provenance_new_artifacts.json`.")
    # ---- calendar + manifest
    cal = json.loads((ROOT / "data" / "metadata" / "nse_calendar_2025_2026.json").read_text())
    man = json.loads((ROOT / "data" / "metadata" / "session_quality_manifest.json").read_text())
    md += ["\n## 4. Calendar and session-quality manifest\n", f"* `data/metadata/nse_calendar_2025_2026.json` - {len(cal['holidays'])} confirmed weekday closures (evidence tiers A/B), {len(cal['special_sessions'])} special sessions, the closing-auction regime, and the Phase 1 calendar errors. SHA-256 `{sha(ROOT / 'data/metadata/nse_calendar_2025_2026.json')[:16]}…`.",
           f"* `data/metadata/session_quality_manifest.json` - {man['counts']['sessions_in_manifest']} sessions: {man['counts']['by_status']}; evaluable {man['counts']['evaluable']}; closing-auction sessions {man['counts']['closing_auction_regime_sessions']}. SHA-256 `{sha(ROOT / 'data/metadata/session_quality_manifest.json')[:16]}…`.",
           "\nEvidence tiers: **A** = several independent secondary sources AND absent from both vendor series; **B** = absent from both vendor series AND on Phase 1's list AND a standard NSE festival (not individually re-verified in Phase 2.1). The NSE circulars themselves were not read directly.\n"]
    # ---- external references
    cmp_ = json.loads((ROOT / "reports" / "phase21" / "redownload_comparison.json").read_text())
    ext = cmp_["external_closes"]
    md += [f"## 5. External reference data ({ext['checked']} published closing values, retrieved 2026-11-01 by web search)\n", "Used only as an independent check on the vendor data; never written into any dataset.\n",
           "| date | published close | source | vendor daily close | match | 15:30 minute print | match |", "|---|---|---|---|---|---|---|"]
    for e in ext["detail"]:
        md.append(f"| {e['date']} | {e['published_close']} | {e['source']} | {e['vendor_daily_close']} | {'yes' if e['matches'] else '**no**'} | {e['minute_1530_print']} | {'yes' if e['stub_matches'] else 'no'} |")
    md += [f"\nResult: the vendor daily close matches **{ext['vendor_daily_matches']} of {ext['checked']}**; the 15:30 minute print matches **{ext['minute_1530_print_matches']} of {ext['checked']}**.\n",
           "Other external evidence used: NSE Closing Auction Session rollout (Groww, Sahi, IIFL/Oquilia notes); NSE closures on 2026-01-15, 03-26, 03-31, 05-28 (Free Press Journal, The Week, Business Today, Fyers, Outlook Money); NIFTY lot-size revision to 65 (Zerodha/Angel One/Bigul summaries of the NSE circular). All are secondary sources; none is an NSE circular read directly.\n",
           "## 6. What was NOT changed\n", "* No stored candle was replaced (0). No candle was interpolated, forward-filled or reconstructed.", f"* The Phase 1 files `data/metadata/nifty50_instrument.json` (contains a leaked `MagicMock` string) and `download_manifest.json`: {_same_as_archive()}",
           "* The original workbook and the original documents are untouched."]
    (ROOT / "docs" / "phase2" / "data_provenance.md").write_text("\n".join(md) + "\n")
    print("ok")


if __name__ == "__main__":
    main()
