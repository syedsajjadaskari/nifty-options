"""Phase 2.2: generate docs/phase2/phase22_final_rule_matrix.md from the rule registry (single source of truth)."""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nifty_trading.strategies.params import DEFAULT_PROPOSALS, DEFAULT_TRADE, T2_CONFLICTS  # noqa: E402
from nifty_trading.strategies.rule_data import RULES  # noqa: E402
from nifty_trading.strategies.rules import IMPLEMENTATIONS  # noqa: E402

ORDER = ["IRF", "ORB", "PDR", "PDS", "RF", "EXEC", "DATA", "ALL"]
AB = {"VERIFIED_EXPLICIT": "VE", "VERIFIED_QUALITATIVE": "VQ", "CONFLICTING": "CF", "UNRESOLVED": "UN", "PROPOSED_FOR_REVIEW": "PR", "USER_APPROVED": "UA"}


def main() -> None:
    tested = {r for fn, ids in IMPLEMENTATIONS.items() for r in ids}
    md = ["# Phase 2.2 final rule matrix (generated by scripts/phase22_build_docs.py from the registry)\n",
          "Labels: **VE** verified explicit · **VQ** verified qualitative (needs a number) · **CF** conflicting · **UN** unresolved · **PR** proposed for review · **UA** user-approved. "
          "`mandatory=Y` rules gate a strategy. Nothing here is `VERIFIED` end-to-end: see `phase3_readiness.md`.\n",
          "## Parameters in force (defaults)\n",
          "| item | value | status |", "|---|---|---|"]
    for st in ("IRF", "ORB", "PDR", "PDS", "RF"):
        md.append(f"| {st} stop | {DEFAULT_TRADE.stop_points(st)} (alternate {40.0 if st != 'ORB' else 30.0}) | {DEFAULT_TRADE.stop_status(st)} |")
        md.append(f"| {st} Target 2 | {DEFAULT_TRADE.t2_points(st)} | {DEFAULT_TRADE.t2_status(st)}" + (f" - conflict recorded: {T2_CONFLICTS[st]}" if st in T2_CONFLICTS else "") + " |")
    md.append(f"| Target 1 / legs | {DEFAULT_TRADE.t1_points} points on 3 of 6 lots, stop to entry afterwards | VERIFIED_EXPLICIT (performance report) |")
    p = DEFAULT_PROPOSALS
    for k in ("trend_mode", "swing_k", "strong_candle", "pin_bar", "small_candle_body_ratio_max", "pdr_zone_method", "zone_lower_boundary", "pds_zone_method",
              "pds_zone_upper_boundary", "zone_proximity_points", "pdr_open_vs_zone", "pds_open_vs_zone", "irf_support_def", "m3_compression_def", "max_signals_per_session"):
        md.append(f"| `{k}` | `{getattr(p, k)}` | PROPOSED_FOR_REVIEW |")
    summary = {}
    for st in ORDER:
        rs = [r for r in RULES if r["strategy"] == st]
        if not rs:
            continue
        c = Counter(AB[r["classification"]] for r in rs)
        mand_open = [r["rule_id"] for r in rs if r["mandatory"] and r["classification"] in ("CONFLICTING", "UNRESOLVED", "PROPOSED_FOR_REVIEW")]
        summary[st] = (len(rs), dict(c), mand_open)
        md += [f"\n## {st}\n", "| rule | status | mandatory | implementation | proposal key | tested | description |", "|---|---|---|---|---|---|---|"]
        for r in rs:
            desc = r["description"].replace("|", "/")
            md.append(f"| {r['rule_id']} | {AB[r['classification']]} | {'Y' if r['mandatory'] else 'N'} | {r['implementation_status'].replace('IMPLEMENTED_', '').replace('NOT_IMPLEMENTED_', 'NOT_')} | "
                      f"{r['proposal_parameter'] or ''} | {'Y' if r['rule_id'] in tested else ''} | {desc[:230]}{'...' if len(desc) > 230 else ''} |")
    md += ["\n## Mandatory rules that are not VERIFIED (per strategy)\n", "| strategy | rules | by status | mandatory but CF/UN/PR |", "|---|---|---|---|"]
    for st, (n, c, mo) in summary.items():
        md.append(f"| {st} | {n} | {c} | {len(mo)}: {', '.join(mo)} |")
    (ROOT / "docs" / "phase2" / "phase22_final_rule_matrix.md").write_text("\n".join(md) + "\n")
    print({k: (v[0], len(v[2])) for k, v in summary.items()})


if __name__ == "__main__":
    main()
